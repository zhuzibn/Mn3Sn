function cfg=mn3sn_default_config(varargin)
%MN3SN_DEFAULT_CONFIG Editable production inputs; SI units except angles in deg.
% cfg=mn3sn_default_config('fig5a',300); cfg.protocol holds all drive/time inputs.
root=fileparts(mfilename('fullpath'));original=pwd;original_path=path;
cleanup=onCleanup(@() restore(original,original_path));
cd(root);addpath(root,'-begin');constantfile;
cfg=struct('protocol',mn3sn_protocol(varargin{:}), ...
    'rk4',1,'bc',0,'DMIenable',1,'dwcalc',0,'thermalenable',0, ...
    'loadstartm',0,'load_fixed_atom_distrib',0,'save_fixed_atom_distrib',0, ...
    'dipolemode',0,'enablefixedge',0, ...
    'd',0.4e-9,'Ksim',0.196*1e-3*ele,'Jintra',100.812*(3*mub), ...
    'gamRE',gam,'tz',30e-9,'volume',0.3778e-27,'musRE',3*mub, ...
    'msRE',441.85e3,'Dsim',0.833*1e-3*ele,'alp',0.003, ...
    'SOT_DLT',1,'SOT_FLT',0,'psjSHE',[1 0 0],'thetaSH',0.06,'chi',0, ...
    'jcSTT',0,'STT_DLT',0,'STT_FLT',0,'psjSTT',[0 0 1],'etaSTT',0.8,'chiSTT',0, ...
    'T',100,'gpu_device',1,'rng_seed',[],'initial_state',[]);
end

function restore(folder,oldpath)
cd(folder);path(oldpath);
end
